# Функция для получения описания карточки
def get_card_description(profile_code):
    """
    Возвращает описание карточки для заданного профиля
    
    Args:
        profile_code: код профиля (например, "SA_7_val")
    
    Returns:
        dict: словарь с полями title, pain, world, superpower, growth, cta
        или None, если профиль не найден
    """
    return CARD_DESCRIPTIONS.get(profile_code)

# Функция для форматирования полного описания
def format_full_description(profile_code):
    """
    Форматирует полное описание карточки для отображения
    
    Args:
        profile_code: код профиля
    
    Returns:
        str: отформатированное описание или сообщение об ошибке
    """
    card = get_card_description(profile_code)
    
    if not card:
        return f"❌ Описание для профиля {profile_code} не найдено"
    
    return f"""{card['title']}

{card['pain']}

{card['world']}

{card['superpower']}

{card['growth']}

{card['cta']}"""

# Функция для получения списка всех профилей
def get_all_profiles():
    """Возвращает список всех доступных кодов профилей"""
    return list(CARD_DESCRIPTIONS.keys())

# Функция для проверки наличия профиля
def profile_exists(profile_code):
    """Проверяет, существует ли описание для данного профиля"""
    return profile_code in CARD_DESCRIPTIONS

# Статистика
def get_stats():
    """Возвращает статистику по описаниям"""
    total = len(CARD_DESCRIPTIONS)
    
    # Подсчёт по типам
    sa_count = len([k for k in CARD_DESCRIPTIONS.keys() if k.startswith('SA_')])
    ia_count = len([k for k in CARD_DESCRIPTIONS.keys() if k.startswith('IA_')])
    sp_count = len([k for k in CARD_DESCRIPTIONS.keys() if k.startswith('SP_')])
    ip_count = len([k for k in CARD_DESCRIPTIONS.keys() if k.startswith('IP_')])
    cv_count = len([k for k in CARD_DESCRIPTIONS.keys() if k.startswith('CV_')])
    
    return {
        'total': total,
        'by_type': {
            'SA (Социально-Аффилиативный)': sa_count,
            'IA (Экзистенциально-Рефлексивный)': ia_count,
            'SP (Инструментально-Достиженческий)': sp_count,
            'IP (Структурно-Аналитический)': ip_count,
            'CV (Честолюбиво-Властный)': cv_count
        }
    }
