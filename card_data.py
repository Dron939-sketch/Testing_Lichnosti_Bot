# Функции для работы с описаниями

def get_card_description(profile_code):
    """Возвращает описание карточки для профиля"""
    return CARD_DESCRIPTIONS.get(profile_code)

def format_full_description(profile_code):
    """Форматирует полное описание профиля"""
    card = get_card_description(profile_code)
    if not card:
        return f"❌ Описание для профиля {profile_code} не найдено"
    
    return f"""{card['title']}

{card['pain']}

{card['world']}

{card['superpower']}

{card['growth']}

{card['cta']}"""

def get_all_profiles():
    """Возвращает список всех профилей"""
    return list(CARD_DESCRIPTIONS.keys())

def profile_exists(profile_code):
    """Проверяет существование профиля"""
    return profile_code in CARD_DESCRIPTIONS

def get_stats():
    """Возвращает статистику по профилям"""
    total = len(CARD_DESCRIPTIONS)
    sa = len([k for k in CARD_DESCRIPTIONS if k.startswith('SA_')])
    ia = len([k for k in CARD_DESCRIPTIONS if k.startswith('IA_')])
    sp = len([k for k in CARD_DESCRIPTIONS if k.startswith('SP_')])
    ip = len([k for k in CARD_DESCRIPTIONS if k.startswith('IP_')])
    cv = len([k for k in CARD_DESCRIPTIONS if k.startswith('CV_')])
    
    return {
        'total': total,
        'by_type': {
            'SA': sa, 'IA': ia, 'SP': sp, 'IP': ip, 'CV': cv
        }
    }
