def get_card_description(profile_code: str) -> dict:
    """Возвращает описание карточки для профиля"""
    return CARD_DATA.get(profile_code)


def format_full_description(profile_code: str) -> str:
    """Форматирует полное описание профиля"""
    card = get_card_description(profile_code)
    if not card:
        return f"❌ Описание для профиля {profile_code} не найдено"
    
    return f"""{card['title']}

{card['pain']}

{card['world']}

{card['superpower']}

{card['growth']}

{card['cta']}"""


def get_all_profiles() -> list:
    """Возвращает список всех профилей"""
    return list(CARD_DATA.keys())


def profile_exists(profile_code: str) -> bool:
    """Проверяет существование профиля"""
    return profile_code in CARD_DATA


def get_stats() -> dict:
    """Возвращает статистику по профилям"""
    total = len(CARD_DATA)
    sa = len([k for k in CARD_DATA if k.startswith('SA_')])
    ia = len([k for k in CARD_DATA if k.startswith('IA_')])
    sp = len([k for k in CARD_DATA if k.startswith('SP_')])
    ip = len([k for k in CARD_DATA if k.startswith('IP_')])
    
    return {
        'total': total,
        'by_type': {
            'SA': sa,
            'IA': ia,
            'SP': sp,
            'IP': ip
        }
    }


def get_profiles_by_type(type_code: str) -> dict:
    """
    Получить все профили определенного типа
    
    Args:
        type_code: Код типа (SA, IA, SP, IP)
        
    Returns:
        dict: Профили указанного типа
    """
    return {k: v for k, v in CARD_DATA.items() if k.startswith(type_code + '_')}


def get_profiles_by_level(level: int) -> dict:
    """
    Получить все профили определенного уровня
    
    Args:
        level: Уровень мышления (1-9)
        
    Returns:
        dict: Профили указанного уровня
    """
    return {k: v for k, v in CARD_DATA.items() if v["thinking_level"] == level}


def get_profile_by_code(profile_code: str) -> dict:
    """
    Получить профиль по коду
    
    Args:
        profile_code: Код профиля (например, "SA_3_con")
        
    Returns:
        dict: Данные профиля или None
    """
    return CARD_DATA.get(profile_code)


