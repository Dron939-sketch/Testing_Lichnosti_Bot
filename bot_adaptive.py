def get_discrepancy_note(profile_data: dict, actual_profile_key: str) -> str:
    """
    Формирует примечание о конфликте уровней Дилтса.
    Смягченная логика: конфликт ТОЛЬКО при полном несоответствии.
    Если конфликта нет - возвращает пустую строку.
    """
    if not profile_data or not actual_profile_key:
        logger.warning(f"⚠️ get_discrepancy_note: данные отсутствуют - profile_data: {bool(profile_data)}, actual_profile_key: {bool(actual_profile_key)}")
        return ""
    
    try:
        # Получаем тип и уровень из profile_data
        profile_type = profile_data.get('type_code', '').lower()
        profile_level = profile_data.get('level', 1)
        
        # Получаем суффикс из актуального ключа профиля
        parts = actual_profile_key.lower().split('_')
        if len(parts) >= 3:
            actual_suffix = parts[2]
            
            # СМЯГЧЕННАЯ ЛОГИКА: определяем допустимые суффиксы для уровня
            if profile_level == 1:
                expected_suffixes = ['def']
            elif profile_level == 2:
                expected_suffixes = ['sit']
            elif profile_level == 3:
                expected_suffixes = ['con']
            elif profile_level == 4:
                expected_suffixes = ['exp', 'def']
            elif profile_level == 5:
                expected_suffixes = ['int', 'sit']
            elif profile_level == 6:
                expected_suffixes = ['aut', 'con']
            elif profile_level == 7:
                expected_suffixes = ['val', 'exp', 'int']
            elif profile_level == 8:
                expected_suffixes = ['tra', 'aut']
            elif profile_level == 9:
                expected_suffixes = ['ide', 'val', 'tra']
            else:
                expected_suffixes = ['def', 'sit', 'con', 'exp', 'int', 'aut', 'val', 'tra', 'ide']
            
            # КОНФЛИКТ ТОЛЬКО если суффикс完全不 соответствует уровню
            is_conflict = actual_suffix not in expected_suffixes
            
            if is_conflict:
                # Получаем уровень Дилтса из суффикса
                dilts_level = SUFFIX_TO_DILTS.get(actual_suffix, "ENVIRONMENT")
                
                # Получаем фразу из констант
                conflict_phrase = CONFLICT_PHRASES.get(dilts_level, {})
                note = conflict_phrase.get("note", "")
                
                if note:
                    logger.info(f"✅ Сформировано примечание о конфликте: {profile_type}_{profile_level}_{actual_suffix} (не входит в {expected_suffixes})")
                    return f"{note}\n\n"
                else:
                    return f"🔥 Примечание: Обнаружено несоответствие уровней развития.\n\n"
            
            else:
                logger.info(f"✅ Конфликта нет: {actual_suffix} входит в {expected_suffixes}")
                return ""
        
        return ""
        
    except Exception as e:
        logger.error(f"❌ Ошибка в get_discrepancy_note: {e}")
        return ""

def calculate_thinking_level_by_scores(level_scores_dict):
    """
    Определяет уровень мышления (1-9) по системе баллов.
    Возвращает НАИМЕНЬШИЙ уровень с максимальным количеством баллов.
    """
    if not level_scores_dict:
        return 1
    
    # Преобразуем ключи в int
    numeric_scores = {int(k): v for k, v in level_scores_dict.items() if k.isdigit()}
    
    if not numeric_scores:
        return 1
    
    # Находим максимальное количество баллов
    max_score = max(numeric_scores.values())
    
    # Находим ВСЕ уровни с максимальным баллом
    max_levels = [level for level, score in numeric_scores.items() if score == max_score]
    
    if not max_levels:
        return 1
    
    # ВОЗВРАЩАЕМ НАИМЕНЬШИЙ уровень (базовый уровень развития)
    return min(max_levels)

def calculate_final_level(stage2_level, stage3_scores):
    """
    Финальный уровень с приоритетом поведению,
    но с ограничением на резкие скачки.
    """
    if not stage3_scores:
        return stage2_level
    
    # ПРОВЕРКА НА ПУСТОЙ СПИСОК
    if len(stage3_scores) == 0:
        return stage2_level
    
    stage3_avg = sum(stage3_scores) / len(stage3_scores)
    
    # ОГРАНИЧЕНИЕ: не позволяем скачок более чем на 2 уровня
    if stage3_avg > stage2_level + 2:
        stage3_avg = stage2_level + 2
        logger.info(f"Ограничение: stage3_avg > stage2_level+2, установлено {stage3_avg}")
    if stage3_avg < stage2_level - 2:
        stage3_avg = stage2_level - 2
        logger.info(f"Ограничение: stage3_avg < stage2_level-2, установлено {stage3_avg}")
    
    # БОЛЕЕ КОНСЕРВАТИВНЫЕ ВЕСА
    weighted = stage3_avg * 0.6 + stage2_level * 0.4
    final_level = int(round(weighted))
    
    # ГАРАНТИЯ: уровень в диапазоне 1-9
    final_level = max(1, min(9, final_level))
    
    logger.info(f"Final level: stage2={stage2_level}, stage3_avg={stage3_avg:.2f}, weighted={weighted:.2f}, final={final_level}")
    return final_level

def need_clarification_stage1(scores):
    """Нужны ли уточнения после ЭТАПА 1"""
    external = scores.get("EXTERNAL", 0)
    internal = scores.get("INTERNAL", 0)
    symbolic = scores.get("SYMBOLIC", 0)
    material = scores.get("MATERIAL", 0)
    
    clarifications = []
    if abs(external - internal) <= 2:
        clarifications.append("external_internal")
    if abs(symbolic - material) <= 2:
        clarifications.append("symbolic_material")
    
    return clarifications

def need_clarification_stage2(level_scores_dict):
    """
    Определяет, нужны ли уточнения после этапа 2.
    Уточнения нужны, если баллы между ГРУППАМИ уровней близки.
    Группы: 1-3 (базовые), 4-6 (средние), 7-9 (высокие)
    """
    if not level_scores_dict:
        return False
    
    # Суммируем баллы по группам уровней
    level_groups = {0: 0, 1: 0, 2: 0}  # 0: уровни 1-3, 1: уровни 4-6, 2: уровни 7-9
    
    for level_str, score in level_scores_dict.items():
        level = int(level_str)
        group = (level - 1) // 3  # 0, 1, или 2
        level_groups[group] = level_groups.get(group, 0) + score
    
    # Сортируем группы по баллам
    sorted_groups = sorted(level_groups.items(), key=lambda x: x[1], reverse=True)
    
    # Если есть хотя бы две группы с баллами
    if len(sorted_groups) >= 2:
        first_score = sorted_groups[0][1]
        second_score = sorted_groups[1][1]
        
        # Уточнение нужно, если разница между группами МЕНЬШЕ 5 баллов
        return abs(first_score - second_score) < 5
    
    return False

def need_clarification_stage3(stage2_level, stage3_scores):
    """
    Определяет, нужны ли уточнения после этапа 3.
    Уточнения нужны, если расхождение между мышлением и поведением БОЛЬШЕ 3 уровней.
    """
    if not stage3_scores or len(stage3_scores) < 4:  # Нужно минимум 4 ответа
        return False
    
    stage3_avg = sum(stage3_scores) / len(stage3_scores)
    
    # ПОВЫШЕННЫЙ ПОРОГ: разница больше 3 уровней
    return abs(stage2_level - stage3_avg) > 3

def need_clarification_stage4(dilts_answers):
    """Нужны ли уточнения после ЭТАПА 4"""
    if not dilts_answers:
        return False
    
    counter = Counter(dilts_answers)
    most_common = counter.most_common(2)
    if len(most_common) >= 2:
        return most_common[0][1] == most_common[1][1]
    return False

def check_profile_coherence(profile_level: int, dilts_level: str, actual_suffix: str = None) -> dict:
    """
    Проверяет согласованность уровня профиля и уровня Дилтса.
    Обновленная версия с правильным маппингом.
    """
    # Ожидаемые уровни Дилтса по уровням развития
    expected_dilts_by_level = {
        1: ["ENVIRONMENT"],      # def - базовое окружение
        2: ["BEHAVIOR"],         # sit - ситуативное поведение
        3: ["CAPABILITIES"],     # con - конструктивные способности
        4: ["BEHAVIOR", "CAPABILITIES"],  # exp - эксперименты
        5: ["CAPABILITIES", "VALUES"],    # int - интеграция
        6: ["VALUES"],           # aut - автономия
        7: ["VALUES", "IDENTITY"],  # val - ценности
        8: ["IDENTITY"],         # tra - трансформация
        9: ["IDENTITY"]          # ide - идентичность
    }
    
    # Маппинг суффиксов на ожидаемые уровни
    expected_suffix_by_level = {
        1: ["def"],
        2: ["sit"],
        3: ["con"],
        4: ["exp", "def"],
        5: ["int", "sit"],
        6: ["aut", "con"],
        7: ["val", "exp", "int"],
        8: ["tra", "aut"],
        9: ["ide", "val", "tra"]
    }
    
    expected_dilts = expected_dilts_by_level.get(profile_level, ["VALUES"])
    is_coherent = dilts_level in expected_dilts
    
    # Проверка по суффиксу (если передан)
    suffix_ok = True
    if actual_suffix:
        expected_suffixes = expected_suffix_by_level.get(profile_level, [])
        suffix_ok = actual_suffix in expected_suffixes
    
    return {
        "is_coherent": is_coherent and suffix_ok,
        "profile_level": profile_level,
        "dilts_level": dilts_level,
        "actual_suffix": actual_suffix,
        "expected_dilts": expected_dilts,
        "expected_suffixes": expected_suffix_by_level.get(profile_level, []),
        "coherence_details": {
            "dilts_match": is_coherent,
            "suffix_match": suffix_ok
        }
    }

def clean_duplicate_headers(text: str, field_type: str) -> str:
    """
    Убирает заголовки, которые уже есть в тексте профиля.
    """
    if not text:
        return ""
    
    lines = text.strip().split('\n')
    if not lines:
        return text
    
    headers = {
        'trigger': ['ЭТО ТЫ, ЕСЛИ...', 'ЭТО ТЫ, ЕСЛИ:'],
        'pain': ['СУТЬ ПРОБЛЕМЫ:', 'СУТЬ ПРОБЛЕМЫ: ПОЧЕМУ ЭТО ЛОМАЕТ ТВОЮ ЖИЗНЬ?'],
        'immediate_tool': ['ПЕРВЫЙ ШАГ / ИНСТРУМЕНТ «ПРЯМО СЕЙЧАС»:', 'ИНСТРУМЕНТ «ПРЯМО СЕЙЧАС»:'],
        'cta': ['ЧТО ДАЛЬШЕ?', 'ДАЛЬШЕ:']
    }
    
    if field_type in headers and lines:
        first_line = lines[0].strip()
        for header in headers[field_type]:
            if header in first_line:
                lines.pop(0)
                if lines and not lines[0].strip():
                    lines.pop(0)
                break
    
    return '\n'.join(lines).strip()

def format_profile_title(profile_title: str, profile_header: str) -> str:
    """Форматирует заголовок профиля."""
    if not profile_title:
        return f"🎯 {profile_header}"
    
    profile_title = profile_title.strip()
    lines = profile_title.split('\n')
    
    if len(lines) == 1:
        title = lines[0].strip()
        return f"🎯 {profile_header} / {title}"
    
    elif len(lines) >= 2:
        line1 = lines[0].strip()
        line2 = lines[1].strip()
        
        if line2 == profile_header or line2.replace('_', ' ').lower() == profile_header.replace('_', ' ').lower():
            return f"🎯 {profile_header} / {line1}"
        else:
            return f"🎯 {profile_header} / {line1}"
    
    return f"🎯 {profile_header}"

