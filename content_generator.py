def generate_profile(type_code, level, dilts_code):
    """
    Генерирует профиль на основе типа, уровня и проблемы Дилтса
    
    Args:
        type_code: SA/IA/SP/IP
        level: 1-9
        dilts_code: env/beh/cap/val/ide/mis
    
    Returns:
        dict с полями: type, type_full, level, level_name, dilts, who, behavior, 
                      strengths, dark, money, relationships, integration, link
    """
    
    # Валидация входных данных
    if type_code not in TYPES:
        raise ValueError(f"Unknown type_code: {type_code}. Must be one of {list(TYPES.keys())}")
    
    if level not in LEVELS:
        raise ValueError(f"Unknown level: {level}. Must be 1-9")
    
    if dilts_code not in DILTS:
        raise ValueError(f"Unknown dilts_code: {dilts_code}. Must be one of {list(DILTS.keys())}")
    
    type_data = TYPES[type_code]
    level_data = LEVELS[level]
    dilts_data = DILTS[dilts_code]
    context = TYPE_CONTEXTS[type_code]
    
    # Подставляем контекстные переменные
    def substitute(text):
        return text.format(
            goal=context["goal"],
            goal_basic=context["goal_basic"],
            achievement=context["achievement"],
            area=context["area"],
            context=context["context"],
            first_step=context["first_step"],
            pain=context["pain"],
            money_context=context["money_context"],
            rel_goal=context["rel_goal"],
            rel_behavior=context["rel_behavior"],
            rel_achievement=context["rel_achievement"],
        )
    
