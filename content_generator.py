def generate_all_profiles():
    """Генерирует все 216 комбинаций"""
    profiles = {}
    
    types = ["SA", "IA", "SP", "IP"]
    levels = range(1, 10)
    dilts_codes = ["env", "beh", "cap", "val", "ide", "mis"]
    
    for type_code in types:
        for level in levels:
            for dilts_code in dilts_codes:
                key = f"{type_code}_{level}_{dilts_code}"
                profiles[key] = generate_profile(type_code, level, dilts_code)
    
    return profiles

