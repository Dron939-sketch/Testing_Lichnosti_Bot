# ФУНКЦИЯ ГЕНЕРАЦИИ КОНТЕНТА
# ============================================

def generate_profile(type_code, level, dilts_code):
    """
    Генерирует профиль на основе типа, уровня и проблемы Дилтса
    
    Args:
        type_code: SA/IA/SP/IP
        level: 1-9
        dilts_code: env/beh/cap/bel/id/mis
    
    Returns:
        dict с полями: type, level, dilts, who, integration, link
    """
    
    type_data = TYPES[type_code]
    level_data = LEVELS[level]
    dilts_data = DILTS[dilts_code]
    context = TYPE_CONTEXTS[type_code]
    
    # Подставляем контекстные переменные
    def substitute(text):
        return text.format(
            goal=context["goal"],
            goal_basic=context["goal_basic"],
            achievement=context["achievement"],
            area=context["area"],
            context=context["context"],
            first_step=context["first_step"],
            pain=context["pain"],
        )
    
    # Генерируем блок "КТО ТЫ"
    who = f"""{level_data['emoji']} {level_data['title']}

{type_data['core']}

{type_data['focus']} {substitute(level_data['state'])}

Твоя главная тревога — {type_data['fear']}. Твоя главная потребность — {type_data['need']}."""

    # Генерируем блок "ИНТЕГРАЦИЯ"
    integration = f"""{substitute(level_data['trap_intro'])}

Но вот в чём ловушка: {dilts_data['problem']}. {dilts_data['thought']}

Это классическая ловушка — {dilts_data['trap']}. {dilts_data['trap_detail']}.

Что делать? {dilts_data['solution']} {substitute(level_data['action'])}

И тогда ты сможешь научиться быть собой в {context['area']}."""

    return {
        "type": type_data["name"],
        "level": level,
        "dilts": dilts_data["name"],
        "who": who,
        "integration": integration,
        "link": "https://t.me/meysternlp"
    }

# ============================================
# ГЕНЕРАЦИЯ ВСЕХ 216 ПРОФИЛЕЙ
# ============================================

def generate_all_profiles():
    """Генерирует все 216 комбинаций"""
    profiles = {}
    
    types = ["SA", "IA", "SP", "IP"]
    levels = range(1, 10)
    dilts_codes = ["env", "beh", "cap", "bel", "id", "mis"]
    
    for type_code in types:
        for level in levels:
            for dilts_code in dilts_codes:
                key = f"{type_code}_{level}_{dilts_code}"
                profiles[key] = generate_profile(type_code, level, dilts_code)
    
    return profiles

